// Independent ISO/IEC 18004 Section 7.9.1 BCH(15,5) format-information table
// Generator polynomial: G(x) = x^10 + x^8 + x^5 + x^4 + x^2 + x + 1 (0x537), mask 0x5412.
// Note: in QR format info, EC level L is 0b01 (M=00, L=01, H=10, Q=11).
function buildFormatTable(): Array<{ ec: number; mask: number; codeword: number }> {
  const entries: Array<{ ec: number; mask: number; codeword: number }> = []
  for (let ec = 0; ec < 4; ec++) {
    for (let mask = 0; mask < 8; mask++) {
      const data = (ec << 3) | mask
      let rem = data << 10
      for (let bit = 14; bit >= 10; bit--) {
        if ((rem >>> bit) & 1) rem ^= 0x537 << (bit - 10)
      }
      entries.push({ ec, mask, codeword: ((data << 10) | rem) ^ 0x5412 })
    }
  }
  return entries
}

const FORMAT_TABLE = buildFormatTable()

function popcount15(n: number): number {
  let c = 0
  for (let i = 0; i < 15; i++) {
    if ((n >>> i) & 1) c++
  }
  return c
}

function readBitsMsbFirst(matrix: boolean[][], coords: ReadonlyArray<readonly [number, number]>): number {
  let word = 0
  for (const [r, c] of coords) {
    word = (word << 1) | (matrix[r][c] ? 1 : 0)
  }
  return word
}

function decodeFormatWord(word: number): { ec: number; mask: number; distance: number } {
  let best = { ec: -1, mask: -1, distance: 16 }
  for (const entry of FORMAT_TABLE) {
    const distance = popcount15(word ^ entry.codeword)
    if (distance < best.distance) {
      best = { ec: entry.ec, mask: entry.mask, distance }
    }
  }
  return best
}

function extractFormatCopies(matrix: boolean[][]) {
  const n = matrix.length
  const copy1Coords: Array<readonly [number, number]> = [
    [8, 0], [8, 1], [8, 2], [8, 3], [8, 4], [8, 5],
    [8, 7], [8, 8], [7, 8],
    [5, 8], [4, 8], [3, 8], [2, 8], [1, 8], [0, 8],
  ]
  const copy2Coords: Array<readonly [number, number]> = [
    [n - 1, 8], [n - 2, 8], [n - 3, 8], [n - 4, 8], [n - 5, 8], [n - 6, 8], [n - 7, 8],
    [8, n - 8], [8, n - 7], [8, n - 6], [8, n - 5], [8, n - 4], [8, n - 3], [8, n - 2], [8, n - 1],
  ]
  return {
    copy1Word: readBitsMsbFirst(matrix, copy1Coords),
    copy2Word: readBitsMsbFirst(matrix, copy2Coords),
    darkModule: matrix[n - 8][8],
  }
}

function matrixToStrings(matrix: boolean[][]): string[] {
  return matrix.map((row) => row.map((v) => (v ? '#' : '.')).join(''))
}

