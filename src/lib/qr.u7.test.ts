const TEST_VECTORS = [
  { name: 'Version 1', payload: 'hello', expected: GOLDEN_V1 },
  {
    name: 'Version 5 (Algorand URI)',
    payload: 'algorand://ABCDEFGHIJKLMNOPQRSTUVWXYZ234567ABCDEFGHIJKLMNOPQRSTUVWXYZ?amount=312000',
    expected: GOLDEN_V5,
  },
  { name: 'Version 7', payload: 'V7-' + 'A'.repeat(142), expected: GOLDEN_V7 },
  { name: 'Version 10', payload: 'V10-' + 'B'.repeat(246), expected: GOLDEN_V10 },
] as const

describe('ISO/IEC 18004 QR encoder & FryvpnQr guard', () => {
  for (const vec of TEST_VECTORS) {
    it(`${vec.name}: decodes Copy 1 & Copy 2 format info at distance 0 (EC=L) and matches qrencode bit-for-bit`, () => {
      const matrix = encodeQrMatrix(vec.payload)
      const { copy1Word, copy2Word, darkModule } = extractFormatCopies(matrix)

      expect(darkModule).toBe(true)

      const d1 = decodeFormatWord(copy1Word)
      const d2 = decodeFormatWord(copy2Word)
      expect(d1.distance).toBe(0)
      expect(d2.distance).toBe(0)
      expect(d1.ec).toBe(1) // EC Level L = 0b01
      expect(d2.ec).toBe(1)
      expect(d1.mask).toBeGreaterThanOrEqual(0)
      expect(d1.mask).toBeLessThanOrEqual(7)
      expect(d2.mask).toBe(d1.mask)

      expect(matrixToStrings(matrix)).toEqual(vec.expected)
    })
  }

  it('encodeQrMatrix throws when payload exceeds 271 UTF-8 bytes', () => {
    expect(() => encodeQrMatrix('x'.repeat(272))).toThrow(/too long/i)
    expect(() => encodeQrMatrix('é'.repeat(136))).toThrow(/too long/i)
  })

  it('FryvpnQr returns null instead of throwing when payload exceeds 271 UTF-8 bytes', () => {
    expect(FryvpnQr({ value: 'x'.repeat(272) })).toBeNull()
    expect(FryvpnQr({ value: 'hello' })).not.toBeNull()
  })
})
